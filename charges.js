// Alias for backwards compatibility
const FLAG_CHARGES = COUNTRY_CHARGES;

// Helper to look up country charge by ID, code, or country name
function getChargeById(id) {
  if (!id) return COUNTRY_CHARGES[0];
  const q = String(id).trim().toLowerCase();
  return COUNTRY_CHARGES.find(c => 
    c.code.toLowerCase() === q || 
    c.id.toLowerCase() === q || 
    c.name.toLowerCase() === q
  ) || COUNTRY_CHARGES.find(c => c.name.toLowerCase().includes(q)) || COUNTRY_CHARGES[0];
}

// In-memory cache for loaded SVG vector assets
const CHARGE_SVG_CACHE = {};

// Asynchronously load an SVG file from the /svg/ directory
async function loadChargeSvg(codeOrId) {
  const charge = getChargeById(codeOrId);
  const code = charge ? charge.code : String(codeOrId || '').toLowerCase();
  if (CHARGE_SVG_CACHE[code]) {
    return CHARGE_SVG_CACHE[code];
  }

  try {
    const assetUrl = new URL('svg/' + encodeURIComponent(code) + '.svg', document.baseURI);
    const res = await fetch(assetUrl);
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const svgText = await res.text();
    CHARGE_SVG_CACHE[code] = svgText;
    return svgText;
  } catch (err) {
    console.error('Failed to load SVG for ' + code + ':', err);
    return null;
  }
}

// Prefix all internal SVG IDs, hrefs, and clip-paths so multiple charges do not conflict
function prepareSvgForLayer(svgString, layerId) {
  if (!svgString) return { viewBox: '0 0 100 100', inner: '' };
  const tagMatch = svgString.trim().match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/i);
  if (!tagMatch) {
    return { viewBox: '0 0 100 100', inner: svgString };
  }
  const attrs = tagMatch[1];
  const vbMatch = attrs.match(/viewBox=["']([^"']+)["']/i);
  const viewBox = vbMatch ? vbMatch[1] : '0 0 100 100';
  let inner = tagMatch[2];

  const prefix = 'ch_' + layerId + '_';
  inner = inner.replace(/\bid=(["'])([^"']+)\1/g, (m, q, id) => 'id=' + q + prefix + id + q);
  inner = inner.replace(/\bhref=(["'])#([^"']+)\1/g, (m, q, id) => 'href=' + q + '#' + prefix + id + q);
  inner = inner.replace(/\bxlink:href=(["'])#([^"']+)\1/g, (m, q, id) => 'xlink:href=' + q + '#' + prefix + id + q);
  inner = inner.replace(/url\(#([^)]+)\)/g, (m, id) => 'url(#' + prefix + id + ')');

  return { viewBox, inner };
}

// Pre-fetch SVGs in background to ensure zero latency when adding to flag
function prefetchCountrySvgs() {
  COUNTRY_CHARGES.forEach(c => {
    loadChargeSvg(c.code).catch(() => {});
  });
}
